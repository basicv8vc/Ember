import type { B1AssistantTurnRepository } from '@ember/postgres';
import { FAKE_LLM_MODEL, FakeLlm, realSleeper, type Sleeper } from '@ember/execution';
import { isDomainError } from '@ember/domain';
import { z } from 'zod';
import type { WorkerLogger } from '../logger.js';

/** The text makes the simulation visible even to clients that do not render model metadata. */
export const FAKE_TURN_REPLY_PREFIX = '[Simulated reply — not generated by a live model] ';
export const FAKE_TURN_OUTPUT_TOKEN_BUDGET = 24;
export const FAKE_TURN_POLL_INTERVAL_MS = 500;
export const FAKE_TURN_ERROR_BACKOFF_MS = 1_000;
export const FAKE_TURN_BATCH_SIZE = 50;

export interface PendingAssistantTurn {
  readonly tenantId: string;
  readonly conversationId: string;
  readonly turnId: string;
}

export interface FakeTurnSourceMessage extends PendingAssistantTurn {
  readonly text: string;
  readonly deadlineAt: string;
}

/** Additional discovery/source reads implemented by the new PostgreSQL repository. */
export interface FakeTurnResponderRepository extends Pick<
  B1AssistantTurnRepository,
  'getTurn' | 'finishTurn'
> {
  listRunningTurns(limit?: number): Promise<readonly PendingAssistantTurn[]>;
  getSourceMessage(command: PendingAssistantTurn): Promise<FakeTurnSourceMessage | null>;
}

export interface FakeTurnGenerator {
  generate(
    request: { readonly prompt: string; readonly maxOutputTokens: number },
    signal?: AbortSignal,
  ): Promise<{ readonly text: string }>;
}

export interface FakeTurnResponderSummary {
  readonly examined: number;
  readonly completed: number;
  readonly failed: number;
  readonly timedOut: number;
  readonly skipped: number;
}

export interface FakeTurnResponderOptions {
  readonly repository: FakeTurnResponderRepository;
  readonly generator?: FakeTurnGenerator;
  readonly batchSize?: number;
  readonly intervalMs?: number;
  readonly errorBackoffMs?: number;
  readonly sleep?: Sleeper;
  readonly logger?: Pick<WorkerLogger, 'warn'>;
}

export interface FakeTurnResponderRunner {
  /** Stop is idempotent; `done` resolves after the current DB operation and loop drain. */
  stop(): void;
  readonly done: Promise<void>;
}

const outputTextSchema = z.string().min(1).max(8_000);

/**
 * Build the fake responder without starting work. `processOnce` is directly callable by tests and
 * the future Worker composition root; only an explicit `start()` call begins a background loop.
 */
export function createFakeTurnResponder(options: FakeTurnResponderOptions): {
  processOnce(signal?: AbortSignal): Promise<FakeTurnResponderSummary>;
  sweepExpiredOnce(): Promise<number>;
  start(signal?: AbortSignal): FakeTurnResponderRunner;
} {
  const generator = options.generator ?? new FakeLlm();
  const batchSize = options.batchSize ?? FAKE_TURN_BATCH_SIZE;
  const intervalMs = options.intervalMs ?? FAKE_TURN_POLL_INTERVAL_MS;
  const errorBackoffMs = options.errorBackoffMs ?? FAKE_TURN_ERROR_BACKOFF_MS;
  const wait = options.sleep ?? realSleeper;

  for (const [name, value] of [
    ['batchSize', batchSize],
    ['intervalMs', intervalMs],
    ['errorBackoffMs', errorBackoffMs],
  ] as const) {
    if (!Number.isInteger(value) || value < 1) {
      throw new TypeError(`${name} must be a positive integer`);
    }
  }

  const processOnce = async (signal?: AbortSignal): Promise<FakeTurnResponderSummary> => {
    const counters = { examined: 0, completed: 0, failed: 0, timedOut: 0, skipped: 0 };
    const candidates = await options.repository.listRunningTurns(batchSize);

    for (const candidate of candidates) {
      if (signal?.aborted) {
        counters.skipped += candidates.length - counters.examined;
        break;
      }

      counters.examined += 1;
      const current = await options.repository.getTurn(candidate);

      if (current === null || current.status !== 'running') {
        if (current?.status === 'failed' && current.failure_reason === 'timeout') {
          counters.timedOut += 1;
        } else {
          counters.skipped += 1;
        }
        continue;
      }

      const source = await options.repository.getSourceMessage(candidate);

      // The source may have been deleted after the candidate scan. A missing row is expected in
      // that race; the transaction that cleared the transcript has already removed the Turn too.
      if (source === null) {
        counters.skipped += 1;
        continue;
      }

      let generated: { readonly text: string };

      try {
        generated = await generator.generate(
          { prompt: source.text, maxOutputTokens: FAKE_TURN_OUTPUT_TOKEN_BUDGET },
          signal,
        );
      } catch {
        // Shutdown cancellation abandons only uncommitted in-memory work. A later process can
        // rediscover the still-running Turn. Generator diagnostics are never logged or persisted.
        if (signal?.aborted) {
          counters.skipped += candidates.length - counters.examined + 1;
          break;
        }

        let failed;
        try {
          failed = await options.repository.finishTurn({
            tenantId: candidate.tenantId,
            conversationId: candidate.conversationId,
            turnId: candidate.turnId,
            result: {
              status: 'failed',
              failureReason: 'internal_error',
              safeMessage: 'ignored by the PostgreSQL repository',
            },
          });
        } catch (error) {
          if (isNotFound(error)) {
            counters.skipped += 1;
            continue;
          }
          throw error;
        }

        if (failed.status === 'failed') {
          if (failed.failure_reason === 'timeout') {
            counters.timedOut += 1;
          } else {
            counters.failed += 1;
          }
        } else {
          counters.skipped += 1;
        }
        continue;
      }

      const generatedText = outputTextSchema.safeParse(generated.text);

      if (!generatedText.success) {
        let failed;
        try {
          failed = await options.repository.finishTurn({
            tenantId: candidate.tenantId,
            conversationId: candidate.conversationId,
            turnId: candidate.turnId,
            result: {
              status: 'failed',
              failureReason: 'internal_error',
              safeMessage: 'ignored by the PostgreSQL repository',
            },
          });
        } catch (error) {
          if (isNotFound(error)) {
            counters.skipped += 1;
            continue;
          }
          throw error;
        }

        if (failed.status === 'failed') {
          if (failed.failure_reason === 'timeout') {
            counters.timedOut += 1;
          } else {
            counters.failed += 1;
          }
        } else {
          counters.skipped += 1;
        }
        continue;
      }

      if (signal?.aborted) {
        counters.skipped += candidates.length - counters.examined + 1;
        break;
      }

      let completed;
      try {
        completed = await options.repository.finishTurn({
          tenantId: candidate.tenantId,
          conversationId: candidate.conversationId,
          turnId: candidate.turnId,
          result: {
            status: 'completed',
            text: `${FAKE_TURN_REPLY_PREFIX}${generatedText.data}`,
            modelLabel: FAKE_LLM_MODEL,
            simulated: true,
          },
        });
      } catch (error) {
        if (isNotFound(error)) {
          counters.skipped += 1;
          continue;
        }
        throw error;
      }

      if (completed.status === 'completed') {
        counters.completed += 1;
      } else if (completed.status === 'failed') {
        if (completed.failure_reason === 'timeout') {
          counters.timedOut += 1;
        } else {
          counters.failed += 1;
        }
      } else {
        counters.skipped += 1;
      }
    }

    return Object.freeze(counters);
  };

  const sweepExpiredOnce = async (): Promise<number> => {
    const candidates = await options.repository.listRunningTurns(batchSize);
    let expired = 0;

    for (const candidate of candidates) {
      const current = await options.repository.getTurn(candidate);

      if (current?.status === 'failed' && current.failure_reason === 'timeout') {
        expired += 1;
      }
    }

    return expired;
  };

  const start = (parentSignal?: AbortSignal): FakeTurnResponderRunner => {
    const controller = new AbortController();
    const stop = (): void => controller.abort();
    const stopFromParent = (): void => stop();

    if (parentSignal?.aborted) {
      stop();
    } else {
      parentSignal?.addEventListener('abort', stopFromParent, { once: true });
    }

    const done = (async (): Promise<void> => {
      try {
        while (!controller.signal.aborted) {
          try {
            await processOnce(controller.signal);
          } catch (error) {
            // Categories are selected only by built-in Error class. The value, its message and
            // user source text are never stringified or passed to the logger.
            options.logger?.warn('fake assistant turn iteration failed', {
              category: safeErrorCategory(error),
            });

            try {
              await wait(errorBackoffMs, controller.signal);
            } catch {
              if (!controller.signal.aborted) {
                options.logger?.warn('fake assistant turn backoff failed');
              }
            }
            continue;
          }

          if (controller.signal.aborted) {
            break;
          }

          try {
            await wait(intervalMs, controller.signal);
          } catch {
            if (!controller.signal.aborted) {
              options.logger?.warn('fake assistant turn wait failed');
            }
          }
        }
      } finally {
        parentSignal?.removeEventListener('abort', stopFromParent);
      }
    })();

    return Object.freeze({ stop, done });
  };

  return Object.freeze({ processOnce, sweepExpiredOnce, start });
}

function safeErrorCategory(error: unknown): string {
  if (error instanceof TypeError) return 'type_error';
  if (error instanceof RangeError) return 'range_error';
  if (error instanceof SyntaxError) return 'syntax_error';
  if (error instanceof Error) return 'error';
  return 'non_error';
}

function isNotFound(error: unknown): boolean {
  return isDomainError(error) && error.code === 'NOT_FOUND';
}
