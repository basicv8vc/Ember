import { createHash } from 'node:crypto';
import { ModelGatewayFailure } from './errors.js';
import { MODEL_LIMITS, estimateTokensConservative } from './limits.js';
import { clampText } from './providers/shared.js';
import type {
  ConversationTurnInput,
  ConversationTurnOutput,
  ModelCallResult,
  ModelGateway,
  ModelUsage,
  NotesActionItemsInput,
  NotesActionItemsOutput,
  PythonAgentStepInput,
  PythonAgentStepOutput,
} from './types.js';

/** Contains `-fake-`, so no heuristic is needed to recognise simulated text. */
export const FAKE_MODEL_LABEL = 'ember-fake-model-gateway-1';

/** Visible to a client that ignores model metadata; the label above is the machine-readable one. */
export const FAKE_REPLY_PREFIX = '[Simulated reply — not generated by a live model] ';

const FAKE_VOCABULARY = [
  'ember',
  'simulated',
  'deterministic',
  'assistant',
  'gateway',
  'bounded',
  'turn',
  'placeholder',
  'response',
  'no-network',
] as const;

export interface FakeModelGatewayOptions {
  /** Injected wait, so a cancellation test does not need real time. */
  readonly delayMs?: number;
  /** Deterministic failure injection: no provider, no network, same closed taxonomy. */
  readonly failure?: 'model_timeout' | 'model_unavailable' | 'model_rate_limited';
  /** Test-only callback to script a reply or controlled delegation output without keywords. */
  readonly onConversationTurn?: (input: ConversationTurnInput) => ConversationTurnOutput;
  /** Test-only callback to script deterministic notes extraction output. */
  readonly onExtractNotesActionItems?: (input: NotesActionItemsInput) => NotesActionItemsOutput;
  /** Test-only callback to script deterministic Python agent steps. */
  readonly onStepPythonAgent?: (input: PythonAgentStepInput) => PythonAgentStepOutput;
}

/**
 * `fake` mode adapter: zero egress, zero cost, deterministic output.
 *
 * It exists so the whole gate chain — claim, fence, deadline, publication — can be exercised with
 * `simulated: true` and a label that always matches `/-fake-/`. It refuses to run when aborted and
 * never consults the environment, so it cannot accidentally reach a provider.
 */
export class FakeModelGateway implements ModelGateway {
  readonly providerId = 'fake' as const;
  readonly modelLabel = FAKE_MODEL_LABEL;
  readonly simulated = true;
  readonly operations = [
    'conversation.turn',
    'task.notes_action_items',
    'task.python_agent',
  ] as const;

  readonly #delayMs: number;
  readonly #failure: FakeModelGatewayOptions['failure'];
  readonly #onConversationTurn: FakeModelGatewayOptions['onConversationTurn'];
  readonly #onExtractNotesActionItems: FakeModelGatewayOptions['onExtractNotesActionItems'];
  readonly #onStepPythonAgent: FakeModelGatewayOptions['onStepPythonAgent'];

  constructor(options: FakeModelGatewayOptions = {}) {
    this.#delayMs = Math.max(0, Math.trunc(options.delayMs ?? 0));
    this.#failure = options.failure;
    this.#onConversationTurn = options.onConversationTurn;
    this.#onExtractNotesActionItems = options.onExtractNotesActionItems;
    this.#onStepPythonAgent = options.onStepPythonAgent;
  }

  async generateConversationTurn(
    input: ConversationTurnInput,
    signal: AbortSignal,
  ): Promise<ModelCallResult<ConversationTurnOutput>> {
    await this.#beforeExecute(signal);

    if (this.#onConversationTurn !== undefined) {
      const output = this.#onConversationTurn(input);
      return Object.freeze({
        output,
        modelLabel: FAKE_MODEL_LABEL,
        simulated: true as const,
        usage: Object.freeze({
          inputTokens: input.context.reduce(
            (total, message) => total + estimateTokensConservative(message.text),
            0,
          ),
          outputTokens: Math.max(1, estimateTokensConservative(output.text)),
          costMicroUsd: 0,
          rateVersion: 'fake-zero-cost',
        }),
      });
    }

    const maxOutputTokens = Math.min(input.maxOutputTokens, MODEL_LIMITS.maxOutputTokens);
    const seed = createHash('sha256')
      .update(input.turnId)
      .update('\u0000')
      .update(input.context.map((message) => message.text).join('\u0001'))
      .digest();

    const words: string[] = [];

    for (let index = 0; index < Math.max(4, Math.min(16, maxOutputTokens)); index += 1) {
      words.push(FAKE_VOCABULARY[seed[index]! % FAKE_VOCABULARY.length]!);
    }

    const usage: ModelUsage = Object.freeze({
      inputTokens: input.context.reduce(
        (total, message) => total + estimateTokensConservative(message.text),
        0,
      ),
      outputTokens: words.length,
      costMicroUsd: 0,
      rateVersion: 'fake-zero-cost',
    });

    return Object.freeze({
      output: Object.freeze({
        kind: 'reply' as const,
        text: `${FAKE_REPLY_PREFIX}${words.join(' ')}`,
        finishReason: 'stop' as const,
      }),
      modelLabel: FAKE_MODEL_LABEL,
      simulated: true as const,
      usage,
    });
  }

  async extractNotesActionItems(
    input: NotesActionItemsInput,
    signal: AbortSignal,
  ): Promise<ModelCallResult<NotesActionItemsOutput>> {
    await this.#beforeExecute(signal);

    const output: NotesActionItemsOutput =
      this.#onExtractNotesActionItems !== undefined
        ? this.#onExtractNotesActionItems(input)
        : (() => {
            const firstLine =
              input.notes
                .split(/\r?\n/)
                .map((line) => line.trim())
                .find((line) => line.length > 0) ?? 'Notes';
            const summary = clampText(
              `${FAKE_REPLY_PREFIX}Action items for: ${firstLine}`,
              MODEL_LIMITS.resultSummaryMaxChars,
            );
            const detail = clampText(
              `${FAKE_REPLY_PREFIX}\n\n- [ ] Review notes: ${input.notes}`,
              MODEL_LIMITS.resultDetailMaxChars,
            );
            return Object.freeze({
              summaryText: summary.text,
              detailText: detail.text,
              truncated: summary.truncated || detail.truncated,
              finishReason: 'stop' as const,
            });
          })();

    return Object.freeze({
      output,
      modelLabel: FAKE_MODEL_LABEL,
      simulated: true as const,
      usage: Object.freeze({
        inputTokens: estimateTokensConservative(input.notes),
        outputTokens: Math.max(1, estimateTokensConservative(output.detailText)),
        costMicroUsd: 0,
        rateVersion: 'fake-zero-cost',
      }),
    });
  }

  async stepPythonAgent(
    input: PythonAgentStepInput,
    signal: AbortSignal,
  ): Promise<ModelCallResult<PythonAgentStepOutput>> {
    await this.#beforeExecute(signal);

    const output: PythonAgentStepOutput =
      this.#onStepPythonAgent !== undefined
        ? this.#onStepPythonAgent(input)
        : (() => {
            const hasPriorToolResult = input.messages.some((message) => message.role === 'tool');
            if (!hasPriorToolResult && input.remainingPythonCalls > 0) {
              const code = `print("ember-fake-python-ok")`;
              return Object.freeze({
                kind: 'tool_call' as const,
                toolCallId: `fake_call_${input.messages.length + 1}`,
                code,
                purpose: 'run deterministic fake script',
                rawArgumentsJson: JSON.stringify({
                  code,
                  purpose: 'run deterministic fake script',
                }),
              });
            }

            const summary = clampText(
              `${FAKE_REPLY_PREFIX}Completed Python task: ${input.prompt}`,
              MODEL_LIMITS.resultSummaryMaxChars,
            );
            const detail = clampText(
              `${FAKE_REPLY_PREFIX}\n\nExecuted deterministic fake Python agent loop.`,
              MODEL_LIMITS.resultDetailMaxChars,
            );
            return Object.freeze({
              kind: 'final' as const,
              summaryText: summary.text,
              detailText: detail.text,
              truncated: summary.truncated || detail.truncated,
              finishReason: 'stop' as const,
            });
          })();

    const outputChars = output.kind === 'tool_call' ? output.rawArgumentsJson : output.detailText;
    return Object.freeze({
      output,
      modelLabel: FAKE_MODEL_LABEL,
      simulated: true as const,
      usage: Object.freeze({
        inputTokens: Math.max(1, estimateTokensConservative(input.prompt)),
        outputTokens: Math.max(1, estimateTokensConservative(outputChars)),
        costMicroUsd: 0,
        rateVersion: 'fake-zero-cost',
      }),
    });
  }

  async #beforeExecute(signal: AbortSignal): Promise<void> {
    if (signal.aborted) {
      throw new ModelGatewayFailure('client_cancelled');
    }

    if (this.#delayMs > 0) {
      await delay(this.#delayMs, signal);
    }

    if (signal.aborted) {
      throw new ModelGatewayFailure('client_cancelled');
    }

    if (this.#failure !== undefined) {
      throw new ModelGatewayFailure(this.#failure);
    }
  }
}

function delay(ms: number, signal: AbortSignal): Promise<void> {
  if (signal.aborted) {
    return Promise.resolve();
  }

  return new Promise<void>((resolve) => {
    const timer = setTimeout(() => {
      signal.removeEventListener('abort', onAbort);
      resolve();
    }, ms);
    const onAbort = (): void => {
      clearTimeout(timer);
      resolve();
    };
    signal.addEventListener('abort', onAbort, { once: true });
  });
}
